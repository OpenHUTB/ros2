# -*- coding: utf-8 -*-
"""示例轨迹：一条双足行走周期里的 6 个下肢关节关键帧。

数值取自常见的教学用双足步态量级（髋俯仰 ±0.35 rad、膝 0~0.9 rad、踝 ±0.25 rad），
时间轴 0~4.0 s 为一个完整周期（相当于示教时走得比较慢）。它不是某个具体型号的数据，
真机上把 `q_knots` 换成你自己的示教关键帧即可。
"""

import numpy as np

# 6 个关节的顺序（与输出表格一致）
JOINT_NAMES = [
    "hip_pitch_L", "knee_pitch_L", "ankle_pitch_L",
    "hip_pitch_R", "knee_pitch_R", "ankle_pitch_R",
]

# 关键帧时间（s）
T_KNOTS = [0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0]

# 关键帧角度（rad）：n_joints × n_knots
Q_KNOTS = np.array([
    # 左腿：髋摆动 → 支撑 → 回摆
    [0.30, 0.10, -0.25, -0.35, -0.30, -0.05, 0.20, 0.32, 0.30],
    [0.05, 0.35, 0.70, 0.85, 0.60, 0.25, 0.05, 0.02, 0.05],
    [-0.20, -0.10, 0.10, 0.25, 0.15, -0.05, -0.20, -0.25, -0.20],
    # 右腿：与左腿反相
    [-0.30, -0.05, 0.20, 0.32, 0.30, 0.10, -0.25, -0.35, -0.30],
    [0.60, 0.25, 0.05, 0.02, 0.05, 0.35, 0.70, 0.85, 0.60],
    [0.15, -0.05, -0.20, -0.25, -0.20, -0.10, 0.10, 0.25, 0.15],
])

# 各关节的速度/加速度上限（rad/s、rad/s²），教学用保守值
V_MAX = [2.0, 2.5, 2.5, 2.0, 2.5, 2.5]
A_MAX = [8.0, 10.0, 10.0, 8.0, 10.0, 10.0]


def example():
    """返回 (t_knots, q_knots, v_max, a_max)。"""
    return list(T_KNOTS), Q_KNOTS.copy(), list(V_MAX), list(A_MAX)
