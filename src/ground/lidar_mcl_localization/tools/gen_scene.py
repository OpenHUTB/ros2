# -*- coding: utf-8 -*-
"""把 config/scene_layout.py 的唯一墙体定义，同时导出：

    worlds/mcl_room.world     Gazebo 11 场景（纯内联几何，不依赖 model:// 下载）
    maps/mcl_room.pgm         占据栅格（PGM P5，ROS map_server 约定）
    maps/mcl_room.yaml        地图元数据
    results/map_preview.png   预览图（可选，需要 matplotlib）

为什么不用 Gazebo 自带的世界而是自己生成：
    1. 场景下载需要联网，虚拟机里常常拿不到 model://；
    2. 地图必须和场景**像素级一致**，人工画两遍必然对不上；
    3. 墙体改了以后，地图自动跟着改，不会出现"地图与场景不匹配导致定位发散"。

用法（在包根目录下）：
    python3 tools/gen_scene.py
"""

import os
import sys

import numpy as np

PKG_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(PKG_ROOT, "config"))

from scene_layout import (LIDAR_RANGE_MAX, LIDAR_SAMPLES, MAP_PADDING,  # noqa: E402
                          MAP_RESOLUTION, ROOM_SIZE, SPAWN, WALL_HEIGHT,
                          WALL_THICKNESS, WALLS)

WORLD_TEMPLATE = """<?xml version="1.0" ?>
<!-- 由 tools/gen_scene.py 自动生成，请勿手改；改 config/scene_layout.py 后重新生成 -->
<sdf version="1.6">
  <world name="mcl_room">

    <physics type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
    </physics>

    <!-- 光照与全局参数：全部内联，避免 model:// 下载 -->
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.1 0.1 0.1 1</specular>
      <direction>-0.4 0.3 -0.9</direction>
    </light>

    <scene>
      <ambient>0.5 0.5 0.5 1</ambient>
      <background>0.75 0.75 0.78 1</background>
      <shadows>false</shadows>
    </scene>

    <!-- 地面：一个巨大的薄盒子，代替 model://ground_plane -->
    <model name="ground">
      <static>true</static>
      <pose>0 0 -0.005 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>40 40 0.01</size></box></geometry>
          <surface>
            <friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction>
          </surface>
        </collision>
        <visual name="visual">
          <geometry><box><size>40 40 0.01</size></box></geometry>
          <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material>
        </visual>
      </link>
    </model>

    <!-- 墙体：由 WALLS 逐条生成 -->
{wall_models}
  </world>
</sdf>
"""

WALL_MODEL = """    <model name="wall_{idx}">
      <static>true</static>
      <pose>{cx:.4f} {cy:.4f} {hz:.4f} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{sx:.4f} {sz:.4f} {height:.4f}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{sx:.4f} {sz:.4f} {height:.4f}</size></box></geometry>
          <material>
            <ambient>0.85 0.35 0.25 1</ambient>
            <diffuse>0.85 0.35 0.25 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
"""


def build_world():
    blocks = []
    for i, w in enumerate(WALLS):
        blocks.append(WALL_MODEL.format(idx=i, cx=w["cx"], cy=w["cy"],
                                        sx=w["sx"], sz=w["sz"],
                                        height=w.get("height", WALL_HEIGHT),
                                        hz=w.get("height", WALL_HEIGHT) / 2.0))
    return WORLD_TEMPLATE.format(wall_models="\n".join(blocks))


def build_occupancy():
    """把墙体栅格化：墙内 = 占据(0)，其余 = 空闲(254)。

    坐标系：地图原点在左下角（ROS map_server 约定），行索引 0 在图像顶部，
    所以 y 要翻转。
    """
    half_x = ROOM_SIZE[0] / 2.0 + MAP_PADDING
    half_y = ROOM_SIZE[1] / 2.0 + MAP_PADDING
    width = int(round(2 * half_x / MAP_RESOLUTION))
    height = int(round(2 * half_y / MAP_RESOLUTION))

    grid = np.full((height, width), 254, dtype=np.uint8)   # 先全空闲

    # 每个像素中心的世界坐标
    xs = -half_x + (np.arange(width) + 0.5) * MAP_RESOLUTION
    ys = -half_y + (np.arange(height) + 0.5) * MAP_RESOLUTION
    # 行 0 对应 y 最大
    ys_row = ys[::-1]

    for w in WALLS:
        x0 = w["cx"] - w["sx"] / 2.0
        x1 = w["cx"] + w["sx"] / 2.0
        y0 = w["cy"] - w["sz"] / 2.0
        y1 = w["cy"] + w["sz"] / 2.0
        col = (xs >= x0) & (xs <= x1)
        row = (ys_row >= y0) & (ys_row <= y1)
        grid[np.ix_(row, col)] = 0                          # 占据

    # 房间外部标记为未知(205)，让"墙外"与"墙内空闲"区分开
    outer_x = (xs >= -ROOM_SIZE[0] / 2.0) & (xs <= ROOM_SIZE[0] / 2.0)
    outer_y = (ys_row >= -ROOM_SIZE[1] / 2.0) & (ys_row <= ROOM_SIZE[1] / 2.0)
    outside = ~(outer_y[:, None] & outer_x[None, :])
    grid[outside & (grid != 0)] = 205

    origin = (-half_x, -half_y, 0.0)
    return grid, origin, MAP_RESOLUTION


def write_pgm(path, grid):
    height, width = grid.shape
    with open(path, "wb") as fh:
        fh.write(b"P5\n")
        fh.write(b"# generated by tools/gen_scene.py\n")
        fh.write(("%d %d\n" % (width, height)).encode("ascii"))
        fh.write(b"255\n")
        fh.write(grid.astype(np.uint8).tobytes())


def write_yaml(path, image_name, origin, resolution):
    text = (
        "image: %s\n"
        "resolution: %.4f\n"
        "origin: [%.4f, %.4f, %.4f]\n"
        "negate: 0\n"
        "occupied_thresh: 0.65\n"
        "free_thresh: 0.25\n" % (image_name, resolution, origin[0], origin[1], origin[2])
    )
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def main():
    world_dir = os.path.join(PKG_ROOT, "worlds")
    map_dir = os.path.join(PKG_ROOT, "maps")
    os.makedirs(world_dir, exist_ok=True)
    os.makedirs(map_dir, exist_ok=True)

    world_path = os.path.join(world_dir, "mcl_room.world")
    with open(world_path, "w", encoding="utf-8") as fh:
        fh.write(build_world())
    print("[生成] %s（%d 面墙）" % (world_path, len(WALLS)))

    grid, origin, res = build_occupancy()
    pgm_path = os.path.join(map_dir, "mcl_room.pgm")
    yaml_path = os.path.join(map_dir, "mcl_room.yaml")
    write_pgm(pgm_path, grid)
    write_yaml(yaml_path, "mcl_room.pgm", origin, res)

    occupied = int(np.sum(grid == 0))
    free = int(np.sum(grid == 254))
    unknown = int(np.sum(grid == 205))
    print("[生成] %s  %dx%d 像素，%.3f m/px" % (pgm_path, grid.shape[1], grid.shape[0], res))
    print("       占据 %d / 空闲 %d / 未知 %d 像素" % (occupied, free, unknown))
    print("[生成] %s" % yaml_path)
    print("[生成] 出生点 (%.2f, %.2f, yaw=%.2f)" % (SPAWN["x"], SPAWN["y"], SPAWN["yaw"]))
    print("[参数] 激光 %.2f~%.2f m，%d 束" % (0.0, LIDAR_RANGE_MAX, LIDAR_SAMPLES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
