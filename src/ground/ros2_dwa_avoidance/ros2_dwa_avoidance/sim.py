def corridor() -> Scenario:
    return Scenario(
        name="corridor",
        start=(-0.5, 0.0, 0.0),
        goal=(11.5, 0.0),
        circles=[Circle(3.0, 0.25, 0.24), Circle(6.0, -0.28, 0.24), Circle(9.0, 0.20, 0.24)],
        segments=[Segment(-2.0, 0.95, 14.0, 0.95), Segment(-2.0, -0.95, 14.0, -0.95)],
        timeout=60.0,
        description="1.9 m wide corridor with three staggered obstacles",
    )


def doorway() -> Scenario:
    return Scenario(
        name="doorway",
        start=(-0.5, 0.0, 0.0),
        goal=(9.0, 0.0),
        circles=[],
        segments=[
            Segment(5.0, -4.0, 5.0, -0.60),
            Segment(5.0, 0.60, 5.0, 4.0),
        ],
        timeout=60.0,
        description="1.2 m doorway in a long wall",
    )


def clutter(seed: int = 7) -> Scenario:
    rng = random.Random(seed)
    circles: List[Circle] = []
    while len(circles) < 9:
        cx = rng.uniform(1.5, 10.5)
        cy = rng.uniform(-1.6, 1.6)
        r = rng.uniform(0.16, 0.26)
        if math.hypot(cx, cy) < 1.0 or math.hypot(cx - 11.0, cy) < 1.0:
            continue
        if any(math.hypot(cx - c.x, cy - c.y) < r + c.r + 0.75 for c in circles):
            continue
        circles.append(Circle(cx, cy, r))
    return Scenario(
        name="clutter",
        start=(0.0, 0.0, 0.0),
        goal=(11.0, 0.0),
        circles=circles,
        segments=[],
        timeout=60.0,
        description="random cluttered field, seed 7",
    )


def utrap() -> Scenario:
    # U opens toward +x, i.e. away from the robot: a local-minimum trap.
    return Scenario(
        name="utrap",
        start=(0.0, 0.0, 0.0),
        goal=(7.0, 0.0),
        circles=[],
        segments=[
            Segment(5.3, -1.5, 5.3, 1.5),
            Segment(5.3, 1.5, 9.0, 1.5),
            Segment(5.3, -1.5, 9.0, -1.5),
        ],
        timeout=90.0,
        description="U-shaped trap whose opening faces away from the start",
    )


def dynamic() -> Scenario:
    return Scenario(
        name="dynamic",
        start=(-0.5, 0.0, 0.0),
        goal=(11.5, 0.0),
        circles=[],
        segments=[Segment(-2.0, 1.6, 14.0, 1.6), Segment(-2.0, -1.6, 14.0, -1.6)],
        timeout=60.0,
        description="moving obstacle crossing the corridor",
    )


ALL_SCENARIOS = {
    "corridor": corridor,
    "doorway": doorway,
    "clutter": clutter,
    "utrap": utrap,
    "dynamic": dynamic,
}

# Local occupancy grid used by the A* layer (x_min, y_min, x_max, y_max).
GRID_BOUNDS = (-2.0, -6.0, 14.0, 6.0)


def build_params(**overrides) -> DWAParams:
    params = DWAParams()
    for key, value in overrides.items():
        if not hasattr(params, key):
            raise KeyError(f"unknown parameter: {key}")
        setattr(params, key, value)
    return params


# ----------------------------------------------------------------------
# Benchmark entry points
# ----------------------------------------------------------------------
def run_main_benchmark(output: str, figure_dir: str) -> Dict[str, object]:
    params = build_params()
    results: List[SimResult] = []

    for name, factory in ALL_SCENARIOS.items():
        scenario = factory()
        hybrid = AStarDWAController(params, GRID_BOUNDS)
        hybrid.name = "astar_dwa"
        results.append(simulate(scenario, hybrid, params,
                                dynamic_circle=(7.0, -2.2, 0.25, 0.35) if name == "dynamic" else None))

        dwa = DWAController(params)
        dwa.name = "dwa"
        results.append(simulate(scenario, dwa, params,
                                dynamic_circle=(7.0, -2.2, 0.25, 0.35) if name == "dynamic" else None))

        if name in ("corridor", "doorway", "clutter"):
            base = BrakeTurnController()
            base.name = "brake_turn"
            results.append(simulate(scenario, base, params))

    summary = []
    for r in results:
        summary.append({
            "scenario": r.scenario,
            "controller": r.controller,
            "success": r.success,
            "collision": r.collision,
            "time_s": r.time,
            "path_length_m": r.path_length,
            "min_clearance_m": r.min_clearance,
            "final_distance_m": r.final_distance,
            "steps": r.steps,
        })

    payload = {
        "config": params.__dict__,
        "results": summary,
        "episodes": {f"{r.scenario}/{r.controller}": {
            "trajectory": r.trajectory,
            "commands": r.commands,
        } for r in results},
    }
    # Write the data first: a missing matplotlib must not throw away a finished
    # benchmark run.
    with open(output, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=2)
    if figure_dir:
        os.makedirs(figure_dir, exist_ok=True)
        _plot_trajectories(results, figure_dir)
    return payload


def run_parameter_sweep(output: str, figure_dir: str) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for predict_time in (1.0, 1.5, 2.0, 2.5, 3.0):
        for max_v in (0.5, 0.8, 1.1):
            params = build_params(predict_time=predict_time, max_v=max_v)
            for name in ("corridor", "doorway", "clutter"):
                scenario = ALL_SCENARIOS[name]()
                hybrid = AStarDWAController(params, GRID_BOUNDS)
                hybrid.name = "astar_dwa"
                res = simulate(scenario, hybrid, params)
                rows.append({
                    "predict_time": predict_time,
                    "max_v": max_v,
                    "scenario": name,
                    "success": res.success,
                    "time_s": res.time,
                    "min_clearance_m": res.min_clearance,
                    "path_length_m": res.path_length,
                })
    with open(output, "w", encoding="utf-8") as fh:
        json.dump(rows, fh, ensure_ascii=False, indent=2)
    if figure_dir:
        os.makedirs(figure_dir, exist_ok=True)
        _plot_parameter_sweep(rows, figure_dir)
    return rows


# ----------------------------------------------------------------------
# Figures
# ----------------------------------------------------------------------
def _plot_trajectories(results: Sequence[SimResult], figure_dir: str) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    scenarios = {}
    for r in results:
        scenarios.setdefault(r.scenario, []).append(r)

    fig, axes = plt.subplots(2, 3, figsize=(15.0, 8.6))
    axes = axes.ravel()
    styles = {
        "astar_dwa": ("A*+DWA", "-", "#1b9e77", 2.2),
        "dwa": ("DWA", "-", "#d95f02", 1.5),
        "brake_turn": ("brake-turn", "--", "#7570b3", 1.2),
    }
    for ax, (name, runs) in zip(axes, scenarios.items()):
        scenario = ALL_SCENARIOS[name]()
        for s in scenario.segments:
            ax.plot([s.x1, s.x2], [s.y1, s.y2], color="#333333", lw=2.0)
        for c in scenario.circles:
            ax.add_patch(plt.Circle((c.x, c.y), c.r, color="#d95f02", alpha=0.85))
        seen = set()
        for run in runs:
            label, linestyle, color, width = styles.get(
                run.controller, (run.controller, "-", "#666666", 1.2))
            legend_label = label if label not in seen else None
            seen.add(label)
            xs = [p[0] for p in run.trajectory]
            ys = [p[1] for p in run.trajectory]
            ax.plot(xs, ys, linestyle, color=color, lw=width, label=legend_label)
        ax.plot(scenario.start[0], scenario.start[1], "o", color="#1b9e77", ms=8)
        ax.plot(scenario.goal[0], scenario.goal[1], "*", color="#7570b3", ms=14)
        ax.set_title(f"{name}: {scenario.description}", fontsize=9)
        ax.set_xlabel("x [m]")
        ax.set_ylabel("y [m]")
        ax.set_aspect("equal", adjustable="datalim")
        ax.grid(alpha=0.25)
        if len(runs) > 1:
            ax.legend(fontsize=8, loc="best")
    for ax in axes[len(scenarios):]:
        ax.axis("off")
    fig.tight_layout()
    fig.savefig(os.path.join(figure_dir, "trajectories.png"), dpi=150)
    plt.close(fig)


def _plot_parameter_sweep(rows: Sequence[Dict[str, object]], figure_dir: str) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    times = sorted({r["predict_time"] for r in rows})
    speeds = sorted({r["max_v"] for r in rows})
    fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.0))
    for max_v in speeds:
        success = []
        duration = []
        for t in times:
            subset = [r for r in rows if r["predict_time"] == t and r["max_v"] == max_v]
            success.append(100.0 * sum(1 for r in subset if r["success"]) / len(subset))
            duration.append(sum(r["time_s"] for r in subset) / len(subset))
        axes[0].plot(times, success, "o-", label=f"v_max={max_v:.1f} m/s")
        axes[1].plot(times, duration, "o-", label=f"v_max={max_v:.1f} m/s")
    axes[0].set_xlabel("prediction horizon [s]")
    axes[0].set_ylabel("success rate [%]")
    axes[0].set_ylim(-5, 105)
    axes[0].grid(alpha=0.3)
    axes[0].legend(fontsize=8)
    axes[1].set_xlabel("prediction horizon [s]")
    axes[1].set_ylabel("mean completion time [s]")
    axes[1].grid(alpha=0.3)
    axes[1].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(figure_dir, "parameter_sweep.png"), dpi=150)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="DWA offline benchmark")
    parser.add_argument("--out", default="results.json")
    parser.add_argument("--figdir", default="figures")
    parser.add_argument("--sweep-out", default="sweep.json")
    parser.add_argument("--skip-sweep", action="store_true")
    parser.add_argument("--no-figures", action="store_true",
                        help="skip matplotlib plots; results JSON is still written")
    args = parser.parse_args()

    figdir = "" if args.no_figures else args.figdir
    payload = run_main_benchmark(args.out, figdir)
    for row in payload["results"]:
        print("{scenario:9s} {controller:10s} success={success} collision={collision} "
              "time={time_s:5.1f}s path={path_length_m:6.2f}m clear={min_clearance_m:5.2f}m"
              .format(**row))
    if not args.skip_sweep:
        run_parameter_sweep(args.sweep_out, figdir)
        print("parameter sweep written to", args.sweep_out)


if __name__ == "__main__":
    main()


