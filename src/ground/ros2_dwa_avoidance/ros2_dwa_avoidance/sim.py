"""Offline 2-D simulator and benchmark for the DWA planner.

The simulator is intentionally dependency-light (NumPy only) so that the
experiments in the accompanying document can be reproduced without ROS,
Gazebo or a GPU.  Obstacles are either circles or line segments; a synthetic
360-degree laser scan is generated by ray casting and is the only exteroceptive
input consumed by the controllers.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import random
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

try:  # package import (colcon / pytest)
    from .dwa_core import DWA, DWAParams, RobotState, clamp, wrap_angle
    from .hybrid_planner import AStarDWAController
except ImportError:  # direct execution: python sim.py
    from dwa_core import DWA, DWAParams, RobotState, clamp, wrap_angle
    from hybrid_planner import AStarDWAController


# ----------------------------------------------------------------------
# World primitives
# ----------------------------------------------------------------------
@dataclass
class Circle:
    x: float
    y: float
    r: float


@dataclass
class Segment:
    x1: float
    y1: float
    x2: float
    y2: float


@dataclass
class Scenario:
    name: str
    start: Tuple[float, float, float]
    goal: Tuple[float, float]
    circles: List[Circle] = field(default_factory=list)
    segments: List[Segment] = field(default_factory=list)
    timeout: float = 60.0
    description: str = ""


def _raycast(origin: Tuple[float, float], yaw: float, circles: Sequence[Circle],
             segments: Sequence[Segment], n_rays: int, max_range: float) -> Tuple[np.ndarray, np.ndarray]:
    """Return (ranges, world_points) for a full 360-degree scan.

    Beams that hit nothing keep ``inf`` and are excluded from ``world_points``:
    a max-range return means "free space", not "obstacle at max range".
    """
    angles = np.linspace(-math.pi, math.pi, n_rays, endpoint=False) + yaw
    dirs = np.column_stack([np.cos(angles), np.sin(angles)])
    ox, oy = origin
    ranges = np.full(n_rays, np.inf, dtype=float)

    if circles:
        cx = np.array([c.x for c in circles])[None, :]
        cy = np.array([c.y for c in circles])[None, :]
        cr = np.array([c.r for c in circles])[None, :]
        ocx = cx - ox
        ocy = cy - oy
        proj = dirs[:, 0:1] * ocx + dirs[:, 1:2] * ocy
        perp2 = ocx * ocx + ocy * ocy - proj * proj
        disc = cr * cr - perp2
        hit = (disc >= 0.0) & (proj > 0.0)
        t = np.where(hit, proj - np.sqrt(np.maximum(disc, 0.0)), np.inf)
        ranges = np.minimum(ranges, t.min(axis=1))

    if segments:
        p1x = np.array([s.x1 for s in segments])[None, :]
        p1y = np.array([s.y1 for s in segments])[None, :]
        sx = np.array([s.x2 - s.x1 for s in segments])[None, :]
        sy = np.array([s.y2 - s.y1 for s in segments])[None, :]
        qx = p1x - ox
        qy = p1y - oy
        denom = dirs[:, 0:1] * sy - dirs[:, 1:2] * sx
        with np.errstate(divide="ignore", invalid="ignore"):
            t = (qx * sy - qy * sx) / denom
            u = (qx * dirs[:, 1:2] - qy * dirs[:, 0:1]) / denom
        valid = (np.abs(denom) > 1e-12) & (t > 0.0) & (u >= 0.0) & (u <= 1.0)
        t = np.where(valid, t, np.inf)
        ranges = np.minimum(ranges, t.min(axis=1))

    ranges = np.minimum(ranges, max_range)
    valid = np.isfinite(ranges) & (ranges < max_range - 1e-9)
    ranges = np.where(valid, ranges, np.inf)
    xs = ox + ranges[valid] * np.cos(angles[valid])
    ys = oy + ranges[valid] * np.sin(angles[valid])
    return ranges, np.column_stack([xs, ys])


def _distance_to_segment(px: float, py: float, s: Segment) -> float:
    vx, vy = s.x2 - s.x1, s.y2 - s.y1
    wx, wy = px - s.x1, py - s.y1
    length2 = vx * vx + vy * vy
    if length2 < 1e-12:
        return math.hypot(px - s.x1, py - s.y1)
    t = clamp((wx * vx + wy * vy) / length2, 0.0, 1.0)
    return math.hypot(px - (s.x1 + t * vx), py - (s.y1 + t * vy))


def world_clearance(pose: Tuple[float, float], circles: Sequence[Circle],
                    segments: Sequence[Segment]) -> float:
    """Distance from the robot centre to the nearest obstacle surface."""
    x, y = pose
    best = float("inf")
    for c in circles:
        best = min(best, math.hypot(x - c.x, y - c.y) - c.r)
    for s in segments:
        best = min(best, _distance_to_segment(x, y, s))
    return best


# ----------------------------------------------------------------------
# Controllers
# ----------------------------------------------------------------------
class DWAController:
    def __init__(self, params: DWAParams) -> None:
        self.planner = DWA(params)
        self.params = params
        self.last: Optional[object] = None

    def __call__(self, state: RobotState, goal: Tuple[float, float],
                 points: np.ndarray) -> Tuple[float, float]:
        self.last = self.planner.plan(state, goal, points)
        return self.last.v, self.last.w


class BrakeTurnController:
    """Reactive baseline: drive straight, brake and spin when blocked.

    This is the kind of three-state behaviour used by many introductory
    obstacle-avoidance examples; it has no prediction and no velocity window.
    """

    def __init__(self, cruise_speed: float = 0.55, stop_distance: float = 0.75,
                 max_w: float = 1.8) -> None:
        self.cruise_speed = cruise_speed
        self.stop_distance = stop_distance
        self.max_w = max_w

    def __call__(self, state: RobotState, goal: Tuple[float, float],
                 points: np.ndarray) -> Tuple[float, float]:
        goal_angle = math.atan2(goal[1] - state.y, goal[0] - state.x)
        err = wrap_angle(goal_angle - state.yaw)
        if points.size == 0:
            return self.cruise_speed, clamp(1.8 * err, -self.max_w, self.max_w)
        dx = points[:, 0] - state.x
        dy = points[:, 1] - state.y
        dist = np.hypot(dx, dy)
        # Only beams inside a +-35 degree forward cone matter.
        forward = (dx * math.cos(state.yaw) + dy * math.sin(state.yaw)) > 0.0
        cone = forward & (np.abs(np.arctan2(dy, dx) - state.yaw) < math.radians(35.0))
        front = dist[cone]
        if front.size and front.min() < self.stop_distance:
            left = np.sum((dx[cone] > 0) & (dy[cone] > 0))
            right = np.sum((dx[cone] > 0) & (dy[cone] < 0))
            direction = 1.0 if left >= right else -1.0
            return 0.0, direction * self.max_w
        return self.cruise_speed, clamp(1.8 * err, -self.max_w, self.max_w)


# ----------------------------------------------------------------------
# Simulation
# ----------------------------------------------------------------------
@dataclass
class SimResult:
    scenario: str
    controller: str
    success: bool
    collision: bool
    time: float
    path_length: float
    min_clearance: float
    final_distance: float
    steps: int
    trajectory: List[List[float]]
    commands: List[List[float]]


def simulate(scenario: Scenario, controller, params: DWAParams,
             dynamic_circle: Optional[Tuple[float, float, float, float]] = None,
             n_rays: int = 180, max_range: float = 6.0,
             record: bool = True) -> SimResult:
    """Run one closed-loop episode.

    ``dynamic_circle`` is ``(x, y, radius, vy)``; the circle moves along y and
    is included in both the scan and the collision check.
    """
    p = params
    x, y, yaw = scenario.start
    state = RobotState(x, y, yaw, 0.0, 0.0)
    traj = [[x, y]]
    cmds: List[List[float]] = []
    path_length = 0.0
    min_clear = float("inf")
    t = 0.0
    success = False
    collision = False

    dyn = list(dynamic_circle) if dynamic_circle else None

    while t < scenario.timeout:
        circles = list(scenario.circles)
        if dyn is not None:
            circles.append(Circle(dyn[0], dyn[1], dyn[2]))
            dyn[1] += dyn[3] * p.dt
            if dyn[1] > 2.5:
                dyn[1] = -2.5

        _, points = _raycast((state.x, state.y), state.yaw, circles,
                             scenario.segments, n_rays, max_range)
        v_cmd, w_cmd = controller(state, scenario.goal, points)

        # Actuator limits: the command can never change faster than the motors.
        dv = clamp(v_cmd - state.v, -p.max_acc_v * p.dt, p.max_acc_v * p.dt)
        dw = clamp(w_cmd - state.w, -p.max_acc_w * p.dt, p.max_acc_w * p.dt)
        state.v += dv
        state.w += dw

        # Exact unicycle integration over one period (constant v, w).
        if abs(state.w) < 1e-6:
            nx = state.x + state.v * p.dt * math.cos(state.yaw)
            ny = state.y + state.v * p.dt * math.sin(state.yaw)
        else:
            r = state.v / state.w
            nx = state.x + r * (math.sin(state.yaw + state.w * p.dt) - math.sin(state.yaw))
            ny = state.y - r * (math.cos(state.yaw + state.w * p.dt) - math.cos(state.yaw))
        state.yaw = wrap_angle(state.yaw + state.w * p.dt)

        clear = world_clearance((nx, ny), circles, scenario.segments)
        min_clear = min(min_clear, clear)
        path_length += math.hypot(nx - state.x, ny - state.y)
        state.x, state.y = nx, ny
        t += p.dt

        if record:
            traj.append([state.x, state.y])
            cmds.append([state.v, state.w])

        if clear < 0.0:
            collision = True
            break
        if math.hypot(scenario.goal[0] - state.x, scenario.goal[1] - state.y) < p.goal_tolerance:
            success = True
            break

    final_distance = math.hypot(scenario.goal[0] - state.x, scenario.goal[1] - state.y)
    return SimResult(
        scenario=scenario.name,
        controller=getattr(controller, "name", controller.__class__.__name__),
        success=success,
        collision=collision,
        time=round(t, 2),
        path_length=round(path_length, 2),
        min_clearance=round(min_clear, 3) if math.isfinite(min_clear) else 99.0,
        final_distance=round(final_distance, 3),
        steps=int(round(t / p.dt)),
        trajectory=traj,
        commands=cmds,
    )


